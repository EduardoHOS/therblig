// Generates a human-readable inventory of the corpus, so edit tasks can be written
// against real element names instead of invented ones.
import { parse, project } from '../../backend/core/index.mjs';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, extname, sep } from 'node:path';

function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (extname(p) === '.bpmn') out.push(p);
  }
  return out;
}

const LABEL = {
  start: 'start event', end: 'end event', catch: 'intermediate catch', throw: 'intermediate throw',
  boundary: 'boundary event', task: 'task', user: 'user task', service: 'service task',
  send: 'send task', receive: 'receive task', manual: 'manual task', script: 'script task',
  rule: 'business rule task', subprocess: 'subprocess', call: 'call activity',
  xor: 'XOR gateway', and: 'AND gateway', or: 'OR gateway', event_gw: 'event gateway', complex: 'complex gateway',
};

const files = walk(process.argv[2] || 'bench/corpus');
const out = [];
out.push('# Corpus inventory');
out.push('');
out.push('Auto-generated by `bench/tasks/inventory.mjs`. Every element below is real —');
out.push('write edit tasks against these names and ids.');
out.push('');
out.push('Files are ordered small to large. The strata matter: the whole point of the');
out.push('bake-off is that the naive baseline should fail on the large ones and we need');
out.push('to see whether the structured arm holds up where it does.');
out.push('');

const rows = [];
for (const file of files) {
  const short = file.split(sep).join('/').replace('bench/corpus/', '');
  const xml = readFileSync(file, 'utf8');
  const doc = await parse(xml);
  const ir = project(doc.definitions);
  rows.push({ short, xml, ir, nodes: (ir.nodes || []).length });
}
rows.sort((a, b) => a.nodes - b.nodes);

out.push('| file | nodes | pools | lanes | approx tokens as XML |');
out.push('|---|---|---|---|---|');
for (const r of rows) {
  out.push(`| \`${r.short}\` | ${r.nodes} | ${(r.ir.pools || []).length} | ${(r.ir.lanes || []).length} | ~${Math.ceil(r.xml.length / 4).toLocaleString()} |`);
}
out.push('');
out.push('---');
out.push('');

for (const { short, xml, ir } of rows) {
  const nodes = ir.nodes || [];
  const named = nodes.filter((n) => n.name);
  out.push(`## \`${short}\``);
  out.push('');
  const bits = [`${nodes.length} flow nodes`, `${(ir.flows || []).length} sequence flows`];
  if ((ir.pools || []).length) bits.push(`${ir.pools.length} pools`);
  if ((ir.lanes || []).length) bits.push(`${ir.lanes.length} lanes`);
  if ((ir.messageFlows || []).length) bits.push(`${ir.messageFlows.length} message flows`);
  bits.push(`~${Math.ceil(xml.length / 4).toLocaleString()} tokens as raw XML`);
  out.push(bits.join(' · '));
  out.push('');

  for (const pool of ir.pools || []) out.push(`**Pool** ${pool.name ? `"${pool.name}"` : '(unnamed)'} → process \`${pool.process}\``);
  for (const lane of ir.lanes || []) out.push(`**Lane** ${lane.name ? `"${lane.name}"` : '(unnamed)'} \`${lane.id}\``);
  if ((ir.pools || []).length || (ir.lanes || []).length) out.push('');

  const groups = new Map();
  for (const n of nodes) {
    const k = n.type;
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(n);
  }
  for (const [type, list] of [...groups].sort((a, b) => a[0].localeCompare(b[0]))) {
    const shown = list.filter((n) => n.name).slice(0, 12);
    if (!shown.length) { out.push(`- **${LABEL[type] || type}** ×${list.length} (all unnamed)`); continue; }
    out.push(`- **${LABEL[type] || type}** ×${list.length}: ${shown.map((n) => `"${n.name}" \`${n.id}\`${n.on ? ` on \`${n.on}\`` : ''}${n.event ? ` (${n.event})` : ''}`).join(', ')}${list.length > shown.length ? `, +${list.length - shown.length} more` : ''}`);
  }
  const conditional = (ir.flows || []).filter((f) => f.if || f.name);
  if (conditional.length) {
    out.push(`- **labelled / conditional flows** ×${conditional.length}: ${conditional.slice(0, 6).map((f) => `${f.name ? `"${f.name}"` : ''}${f.if ? ` [${f.if}]` : ''} \`${f.from}\`→\`${f.to}\``).join(', ')}`);
  }
  if (!named.length) out.push('- _no named elements — poor target for English edit tasks_');
  out.push('');
}

const text = out.join('\n');
writeFileSync('bench/tasks/CORPUS-INVENTORY.md', text);
console.log(text.split('\n').slice(0, 40).join('\n'));
console.log(`\n… written to bench/tasks/CORPUS-INVENTORY.md (${text.split('\n').length} lines)`);
